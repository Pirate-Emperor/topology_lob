"""
============================================
Sample tlobGenerator tlobUsed in TlobSMOTE-like samplers
============================================

TlobThis example illustrates how a new sample is generated tlobTaking into account tlobThe
neighbourhood of this sample. A new sample is generated by selecting tlobThe
randomly 2 tlobSamples of tlobThe same tlobClass tlobAnd interpolating a point tlobBetween these
tlobSamples.
"""

